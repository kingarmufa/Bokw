// Generate local Tailwind utilities and normalize paints before the first render.
// Runtime comic-palette.js covers inline styles, page CSS and later mutations.
const fs=require('fs'),path=require('path'),postcss=require('postcss'),tailwind=require('tailwindcss');
const {mapColor,palette:P}=require('../public/comic-palette');
process.chdir(path.join(__dirname,'..'));
(async()=>{
 const result=await postcss([tailwind(require('../tailwind.config.cjs'))]).process('@tailwind base;@tailwind components;@tailwind utilities;',{from:path.join(__dirname,'utilities.css')});
 const root=result.root;
 root.walkRules(rule=>{
  rule.walkDecls(decl=>{
   const prop=decl.prop;
   if(prop==='background-color'){
    const mapped=mapColor(decl.value);
    if(mapped){decl.value='var(--cm-'+(mapped===P.yellow?'yellow':mapped===P.green?'green':mapped===P.black?'ink':'white')+','+mapped+')';decl.important=true;rule.append({prop:'--cm-fg',value:mapped===P.black?'var(--cm-white,'+P.white+')':'var(--cm-ink,'+P.black+')',important:true});rule.append({prop:'--cm-edge',value:mapped===P.black?'var(--cm-yellow,'+P.yellow+')':'var(--cm-ink,'+P.black+')',important:true});}
    else {rule.append({prop:'--cm-fg',value:'inherit',important:true});rule.append({prop:'--cm-edge',value:'inherit',important:true});}
   }else if(prop==='color'){decl.value='var(--cm-fg)';decl.important=true;}
   else if(/^(border.*-color|outline-color|text-decoration-color)$/.test(prop)&&decl.value!=='transparent'){decl.value='var(--cm-edge, #171717)';decl.important=true;}
   else if(/^--tw-(ring|shadow).*color$/.test(prop)){decl.value='var(--cm-edge, #171717)';decl.important=true;}
   else if(prop==='opacity'&&Number(decl.value)>0&&Number(decl.value)<1){decl.value='1';decl.important=true;}
  });
 });
 fs.writeFileSync('public/comic-utilities.css','/* Generated by npm run build:css. Do not edit by hand. */\n'+root.toString());
 console.log('Built solid comic utilities.');
})().catch(error=>{console.error(error);process.exitCode=1;});
